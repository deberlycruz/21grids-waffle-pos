-- 5. check: sales per day and cashier (every day should show both cashiers)
SELECT DATE(CO.OrderDate) AS SaleDate, S.FullName AS Cashier, COUNT(*) AS Orders, SUM(CO.TotalAmount) AS Sales
FROM CustomerOrder AS CO
INNER JOIN Staff AS S ON S.StaffID = CO.CashierID
WHERE CO.Status = 'Completed'
GROUP BY DATE(CO.OrderDate), S.FullName
ORDER BY SaleDate, Cashier;

